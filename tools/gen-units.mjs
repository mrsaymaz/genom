// Generates the unit roster (docs/UNIT_ROSTER.md) and the units concept pages
// (docs/concepts/dark-age-units.html, mythic-age-units.html) from src/data/units.js and src/render/unit-models.js,
// so the docs, the page and the game always show the same units.
// Run: node tools/gen-units.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { AGES, AGE_NAMES, LINES, SPECIALS, ROSTER, HEROES, CREATURES, UNIT_TWISTS, NATION_ORDER, NATION_INFO } from '../src/data/units.js';

const strip = src => src.replace(/^export (const|function|let) /gm, '$1 ');
const fmtCost = c => Object.entries(c).map(([k, v]) => `${v} ${k[0].toUpperCase() + k.slice(1)}`).join(', ');

// ---------- the roster document ----------
function roster() {
  const L = [];
  L.push('# Unit roster', '');
  L.push('Generated by `tools/gen-units.mjs` from `src/data/units.js`. Names and descriptions are player-facing; stats are example values for tuning.', '');
  L.push('## How units work', '');
  L.push('- Every nation has four unit lines: **Worker**, **Infantry**, **Ranged** and one **special** line that fits its element. Each line transforms with every age: a new name, a major new look and stronger stats, like the buildings.');
  L.push('- From the Mythic Age, each nation also has one **hero** (Sanctum) and its **signature creature** (Beast Pen). From the Arcane Age, a **siege engine** (Workshop).');
  L.push('- Counters, in plain words: infantry beats fast units; ranged units beat infantry and guardians; fast units (scouts and chargers) beat ranged units; guardians beat infantry and fast units; healers keep others alive. The element cycle (Fire > Earth > Air > Water > Fire) adds a small extra edge.', '');
  L.push('## Age scaling', '');
  L.push('| Age | HP | Attack | Cost |', '|---|---|---|---|');
  for (const a of AGES) { const s = { dark: [1, 1, 1], mythic: [1.35, 1.3, 1.2], arcane: [1.75, 1.6, 1.4], celestial: [2.2, 2, 1.6] }[a]; L.push(`| ${AGE_NAMES[a]} | ×${s[0]} | ×${s[1]} | ×${s[2]} |`); }
  L.push('');
  L.push('## Dark Age base stats', '');
  L.push('| Line | Trained at | HP | Attack | Range | Speed | Cost | Time | Strong against | Weak against |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const [k, d] of Object.entries(LINES)) { const b = d.base; L.push(`| ${d.label} | ${d.from} | ${b.hp} | ${b.attack} ${d.attackType} | ${b.range} | ${b.speed} | ${fmtCost(b.cost)} | ${b.time} s | ${d.strong} | ${d.weak} |`); }
  for (const n of NATION_ORDER) { const d = SPECIALS[n], b = d.base; L.push(`| ${d.label} (${NATION_INFO[n].team}) | ${d.from} | ${b.hp} | ${b.attack} ${d.attackType} | ${b.range} | ${b.speed} | ${fmtCost(b.cost)} | ${b.time} s | ${d.strong} | ${d.weak} |`); }
  L.push('');
  for (const n of NATION_ORDER) {
    const info = NATION_INFO[n], r = ROSTER[n], sp = SPECIALS[n];
    L.push(`## ${info.team} (${info.element})`, '');
    L.push(`Unit twist: ${UNIT_TWISTS[n].text} Special line: **${sp.label}**. ${sp.role} Ability: **${sp.ability.name}**, ${sp.ability.text.charAt(0).toLowerCase() + sp.ability.text.slice(1)}`, '');
    L.push('| Line | Dark | Mythic | Arcane | Celestial |', '|---|---|---|---|---|');
    for (const line of ['worker', 'infantry', 'ranged', 'special']) L.push(`| ${line === 'special' ? sp.label : LINES[line].label} | ${r[line].map(x => x[0]).join(' | ')} |`);
    L.push(`| Hero | — | ${r.hero.map(x => x[0]).join(' | ')} |`);
    L.push(`| Signature creature | — | ${CREATURES[n]} | Elder form | Celestial form |`);
    L.push(`| Siege | — | — | ${r.siege.join(' | ')} |`);
    L.push('');
    L.push(`Hero: ${HEROES[n].role}. Ability **${HEROES[n].ability.name}**: ${HEROES[n].ability.text}`, '');
    L.push('### Hero', '', '| Age | Name | Look |', '|---|---|---|');
    r.hero.forEach(([name, desc], i) => L.push(`| ${AGE_NAMES[AGES[i + 1]]} | ${name} | ${desc} |`));
    L.push('');
    for (const line of ['worker', 'infantry', 'ranged', 'special']) {
      L.push(`### ${line === 'special' ? sp.label : LINES[line].label}`, '');
      L.push('| Age | Name | Look |', '|---|---|---|');
      r[line].forEach(([name, desc], i) => L.push(`| ${AGE_NAMES[AGES[i]]} | ${name} | ${desc} |`));
      L.push('');
    }
  }
  return L.join('\n');
}

